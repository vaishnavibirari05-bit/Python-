# Bitwise operator:-Bitwise operator which is used to performed operations bit by bit.
# It is directly interact with hardware.

# Bitwise operators work on the binary values (0 and 1) of numbers.
# &  → Bitwise AND
# |  → Bitwise OR
# ^  → Bitwise XOR
# ~  → Bitwise NOT
# << → Left Shift
# >> → Right Shift

a = 3
b = 5
print(a&b)

a = 3
b = 5
print(a|b)

a = 3
b = 5
print(a^b)

a = 5
result = ~a
print(result)


