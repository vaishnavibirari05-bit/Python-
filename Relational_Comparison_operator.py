# Relational Operators Practice
a = 10
b = 20
# Equal to (==)
print("a == b:", a == b)   # False
# Not equal to (!=)
print("a != b:", a != b)   # True

# Greater than (>)
print("a > b:", a > b)     # False

# Less than (<)
print("a < b:", a < b)     # True

# Greater than or equal to (>=)
print("a >= b:", a >= b)   # False

# Less than or equal to (<=)
print("a <= b:", a <= b)   # True

# Extra practice with strings
x = "Ram"
y = "ram"
print("x == y:", x == y)   # False (case-sensitive)
print("x != y:", x != y)   # True
